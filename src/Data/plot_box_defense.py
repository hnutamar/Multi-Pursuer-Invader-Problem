# Global style configuration
sns.set_theme(style="whitegrid")
mpl.rcParams['figure.dpi'] = 300

def plot_kamikaze_capture_time(data_dict, filename="kamikaze_capture_times.png"):
    """
    Plots a box plot for Kamikaze capture times.
    """
    rows = []
    
    # Mapping indices to scenarios and environments
    # Index order: [WithObs_5v1, WithObs_20v8, NoObs_5v1, NoObs_20v8]
    mapping = [
        ("5 vs 1", "With Obstacles"),
        ("20 vs 8", "With Obstacles"),
        ("5 vs 1", "Without Obstacles"),
        ("20 vs 8", "Without Obstacles")
    ]
    
    for model, lists in data_dict.items():
        if not lists or len(lists) != 4:
            continue
            
        for i, (scenario, env) in enumerate(mapping):
            if not lists[i]: # Skip if the list is empty (e.g., model never won so no capture times exist)
                continue
                
            for val in lists[i]:
                # Convert simulation steps to seconds (1 step = 0.02 s)
                time_sec = val * 0.02
                rows.append({
                    "Model": model,
                    "Scenario": scenario,
                    "Environment": env,
                    "Capture Time (s)": time_sec
                })
                
    df = pd.DataFrame(rows)
    
    if df.empty:
        print("No data available to plot!")
        return

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(14, 7), sharey=True)
    colors = ['#4A90E2', '#50C878', '#FF9F43']
    
    # Plot for environment WITHOUT OBSTACLES
    sns.boxplot(data=df[df["Environment"] == "Without Obstacles"], 
                x="Scenario", y="Capture Time (s)", hue="Model", 
                ax=ax1, palette=colors, width=0.4, gap=0.1, fliersize=3)
    
    # Plot for environment WITH OBSTACLES
    sns.boxplot(data=df[df["Environment"] == "With Obstacles"], 
                x="Scenario", y="Capture Time (s)", hue="Model", 
                ax=ax2, palette=colors, width=0.4, gap=0.1, fliersize=3)
    
    # Set titles for both subplots
    ax1.set_title('Kamikaze Target Interception: Without Obstacles', fontsize=16, pad=15)
    ax2.set_title('Kamikaze Target Interception: With Obstacles', fontsize=16, pad=15)
    
    ax1.set_ylabel("Capture Time", fontsize=13)
    ax2.set_ylabel("", fontsize=13)
    
    for ax in [ax1, ax2]:
        ax.set_xlabel('Scenario', fontsize=13)
        sns.despine(ax=ax)
        
        # Y-axis can go up to ~30 seconds (maximum episode duration)
        ax.set_ylim(0, 31)

    # Configure global legend
    handles, labels = ax1.get_legend_handles_labels()
    if handles:
        fig.legend(handles, labels, loc='upper center', ncol=3, frameon=False, fontsize=12)
    
    # Remove local legends to avoid clutter inside the plots
    if ax1.get_legend(): ax1.get_legend().remove()
    if ax2.get_legend(): ax2.get_legend().remove()
        
    plt.tight_layout(rect=[0, 0.03, 1, 0.92])
    if filename:
        plt.savefig(filename, dpi=300, bbox_inches='tight')
    plt.close()

